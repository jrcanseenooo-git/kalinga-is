import { expect, test } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { login, expectNoHorizontalOverflow } from './helpers';

for (const width of [360, 768, 1440]) test(`online intake recovers an earlier-step server error and creates a case at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 1000 });
    await login(page); await page.goto('/cases/create');
    await page.getByRole('button', { name: 'Start CEFMU intake', exact: true }).click();
    await page.getByRole('checkbox', { name: /I provided the privacy notice/ }).check();
    await page.getByRole('combobox', { name: /^How was the privacy notice provided/ }).selectOption('explained_verbally');
    const next = () => page.getByRole('button', { name: 'Continue', exact: true }).click();
    await next(); await page.getByRole('combobox', { name: 'Initial risk level *', exact: true }).selectOption('low');
    await next();
    await page.getByRole('textbox', { name: 'First name *', exact: true }).fill('S'.repeat(81));
    await page.getByRole('textbox', { name: 'Last name *', exact: true }).fill('SyntheticRecovery');
    await page.getByLabel('Date of birth *', { exact: true }).fill('2014-02-16');
    await page.getByRole('combobox', { name: 'Sex *', exact: true }).selectOption('Female');
    await next(); await page.getByRole('checkbox', { name: /Early union/ }).check();
    await next(); await page.getByRole('textbox', { name: 'What is the presenting concern? *', exact: true }).fill('Synthetic concise case opening concern.');
    const submit = async () => {
        await page.getByRole('button', { name: 'Create protected CEFMU case folder', exact: true }).click();
        const dialog = page.getByRole('dialog', { name: 'Create protected CEFMU case folder?', exact: true });
        await expect(dialog).toBeVisible();
        await dialog.getByRole('button', { name: 'Review intake', exact: true }).focus();
        await page.keyboard.press('Tab');
        await expect(dialog.getByRole('button', { name: 'Create case folder', exact: true })).toBeFocused();
        await page.keyboard.press('Escape');
        await expect(dialog).not.toBeVisible();
        await expect(page.getByRole('textbox', { name: 'What is the presenting concern? *', exact: true })).toHaveValue('Synthetic concise case opening concern.');
        await page.getByRole('button', { name: 'Create protected CEFMU case folder', exact: true }).click();
        await page.getByRole('button', { name: 'Create case folder', exact: true }).click();
    };
    await submit();
    const errors = page.getByRole('alert', { name: 'Review intake errors', exact: true });
    await expect(errors).toBeFocused();
    await expect(page.getByRole('textbox', { name: 'First name *', exact: true })).toHaveValue('S'.repeat(81));
    await errors.getByRole('button').first().click();
    await expect(page.getByRole('textbox', { name: 'First name *', exact: true })).toBeFocused();
    await page.getByRole('textbox', { name: 'First name *', exact: true }).fill('SyntheticVerified');
    await next(); await next();
    await expect(page.getByRole('textbox', { name: 'What is the presenting concern? *', exact: true })).toHaveValue('Synthetic concise case opening concern.');
    await expectNoHorizontalOverflow(page);
    const accessibility = await new AxeBuilder({ page }).include('main').analyze();
    expect(accessibility.violations.filter(item => ['critical', 'serious'].includes(item.impact ?? ''))).toEqual([]);
    await submit(); await expect(page).toHaveURL(/\/cases\/\d+$/);
    await expect(page.locator('main')).toContainText('SyntheticVerified');
});

test('online intake local validation announces errors and keyboard navigation retains safety work', async ({ page }) => {
    await login(page); await page.goto('/cases/create');
    await page.getByRole('button', { name: 'Start CEFMU intake', exact: true }).click();
    const next = page.getByRole('button', { name: 'Continue', exact: true });
    await next.click();
    const summary = page.getByRole('alert', { name: 'Review intake errors', exact: true });
    await expect(summary).toBeFocused();
    await expect(page.getByRole('button', { name: /Safety triage/ })).toBeDisabled();
    await summary.getByRole('button').first().click();
    await expect(page.getByRole('checkbox', { name: /I provided the privacy notice/ })).toBeFocused();
    await page.getByRole('checkbox', { name: /I provided the privacy notice/ }).check();
    await page.getByRole('combobox', { name: /^How was the privacy notice provided/ }).selectOption('explained_verbally');
    await next.click();
    await expect(page.locator('fieldset > legend')).toBeFocused();
    await page.getByRole('combobox', { name: 'Initial risk level *', exact: true }).selectOption('high');
    await next.click(); await expect(summary).toBeFocused();
    await summary.getByRole('button').first().click();
    const actions = page.getByRole('textbox', { name: /Immediate action taken/ });
    await expect(actions).toBeFocused(); await actions.fill('Synthetic authorized protection action recorded.');
    await next.click(); await expect(page.locator('fieldset > legend')).toBeFocused();
    await page.getByRole('button', { name: /Safety triage/ }).focus(); await page.keyboard.press('Enter');
    await expect(actions).toHaveValue('Synthetic authorized protection action recorded.');
    await expect(page.locator('fieldset > legend')).toBeFocused();
});
