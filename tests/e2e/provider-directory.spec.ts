import { expect, test } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { accounts, login, expectNoHorizontalOverflow } from './helpers';

for (const width of [360, 768, 1440]) test(`administrator can create and filter provider cards at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 1000 });
    await login(page, accounts.admin); await page.goto('/providers');
    await page.getByLabel('Provider status', { exact: true }).selectOption('inactive');
    await expect(page.getByRole('article').filter({ hasText: 'Synthetic inactive referral partner' })).toContainText('Inactive');
    await page.getByLabel('Provider status', { exact: true }).selectOption('active');
    await expect(page.getByRole('article').filter({ hasText: 'Synthetic inactive referral partner' })).toHaveCount(0);
    await page.getByRole('button', { name: 'Clear provider filters', exact: true }).click();
    const form = page.getByRole('form', { name: 'Add service provider', exact: true });
    const name = `Synthetic provider ${width}`;
    await form.getByLabel('Organization name', { exact: true }).fill(name);
    await form.getByLabel('Service type', { exact: true }).selectOption('__other__');
    await form.getByLabel('Specify other', { exact: true }).fill('Synthetic support');
    await form.getByRole('button', { name: 'Add provider', exact: true }).click();
    await page.locator('#generic-submit-confirm').click();
    await expect(page.getByRole('article').filter({ hasText: name })).toBeVisible();
    await page.getByLabel('Search providers', { exact: true }).fill(name);
    await expect(page.getByRole('article')).toHaveCount(1);
    await page.getByLabel('Provider status', { exact: true }).selectOption('inactive');
    await expect(page.getByText('No providers match your filters.', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Clear provider filters', exact: true }).click();
    await expect(page.getByRole('article').filter({ hasText: name })).toBeVisible();
    await page.reload(); await expect(page.getByRole('article').filter({ hasText: name })).toBeVisible();
    await expectNoHorizontalOverflow(page);
    const accessibility = await new AxeBuilder({ page }).include('main').analyze();
    expect(accessibility.violations.filter(item => ['critical', 'serious'].includes(item.impact ?? ''))).toEqual([]);
});
